ACTIONS_NO_WRITE_PROMPT = """\
Ты — агент действий банка, но prepare-инструментов у тебя НЕТ: этому
пользователю изменения через чат недоступны.

- Вопросы о картах и лимитах — вызови get_my_cards и get_card_limits
  и доложи факты.
- Просьба что-то изменить — не выдумывай инструментов: доложи, что
  изменения для этого аккаунта недоступны в чате, и предложи обратиться
  к оператору поддержки.
"""

TICKETS_PROMPT = """\
Ты — агент эскалации банка: передаёшь обращение живому оператору
поддержки. НЕ задавай уточняющих вопросов: сразу вызови
create_ticket(subject=..., note=...) — subject — тема в несколько слов
из сообщения клиента, note — суть обращения. Доложи номер тикета из
результата. Если create_ticket в наборе нет — доложи, что оформить
обращение не можешь.
"""

PROMPTS = {
    "data": DATA_PROMPT, "ops": OPS_PROMPT, "kb": KB_PROMPT,
    "actions": ACTIONS_PROMPT, "tickets": TICKETS_PROMPT,
}

READ_DEFAULT = ("data", "ops", "kb")


def build_workers(session: Session, agent_ids: tuple[str, ...] = READ_DEFAULT) -> dict:
    """Собрать доменных агентов сессии из перечисленных id.

    В набор каждого агента попадают только инструменты его домена
    (из MCP-пула сессии, уже с JWT-соединениями) — allowlist на уровне
    сборки агента.
    """
    workers = {}
    for agent_id in agent_ids:
        spec = CATALOG.get(agent_id)
        if spec is None:
            continue
        tools = wrap_tools(session, spec["tools"])
        prompt = PROMPTS[agent_id]
        if agent_id == "actions" and "prepare_block_card" not in {t.name for t in tools}:
            prompt = ACTIONS_NO_WRITE_PROMPT  # барьер 1 убрал prepare — агент это знает
        workers[agent_id] = llm.build_agent(
            f"{spec['title']} ({session.login})", prompt, tools=tools,
        )
    return workers
