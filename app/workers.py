"""Доменные агенты сессии: узкие наборы инструментов из read-MCP.

Вместо одного агента со всеми инструментами ассистент собран из
узкоспециализированных: агент данных не может искать в базе знаний,
агент операций не может тронуть карту. Какого агента каким шагом
запустить — решает оркестратор по плану (и гейту), не сами агенты.

Набор инструментов каждого агента задаётся кодом при сборке (build_workers):
это тот же allowlist-принцип, что и в барьере 1, только на уровне агента.
"""
