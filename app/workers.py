from app import llm
from app.wrap import wrap_tools
from app.sessions import Session

# id → (русское имя для плана, инструменты домена)
CATALOG: dict[str, dict] = {
    "data": {
        "title": "агент данных клиента",
        "tools": ["get_my_overview", "get_my_cards", "get_card_limits", "get_my_contacts"],
    },
    "ops": {
        "title": "агент операций",
        "tools": [
            "list_recent_transactions", "find_transactions",
            "get_transaction", "list_commission_rules",
        ],
    },
    "kb": {
        "title": "агент базы знаний",
        "tools": ["search_kb"],
    },
    "actions": {
        "title": "агент действий (карты, лимиты, контакты)",
        "tools": [
            "get_my_cards", "get_card_limits",
            "prepare_block_card", "prepare_set_transfer_limit", "prepare_contacts_update",
        ],
    },
    "tickets": {
        "title": "агент эскалации",
        "tools": ["create_ticket"],
    },
}

